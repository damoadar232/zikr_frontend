package db.migration;

import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;

class V17LyricSubjectsMigrationTest {

    @Test
    void safelyAddsSubjectsMappingsAndPreservesExistingAssignmentsOnReapplication() throws Exception {
        try (Connection connection = DriverManager.getConnection("jdbc:h2:mem:subject-migration;DB_CLOSE_DELAY=-1");
                Statement statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE lyric_subjects (
                        id VARCHAR(80) PRIMARY KEY,
                        name VARCHAR(120) NOT NULL UNIQUE
                    )
                    """);
            statement.execute("""
                    CREATE TABLE subject_numeric_mappings (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        subject_key VARCHAR(80) NOT NULL UNIQUE,
                        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        FOREIGN KEY (subject_key) REFERENCES lyric_subjects (id)
                    )
                    """);
            statement.execute("""
                    CREATE TABLE lyric_subject_assignments (
                        lyric_id BIGINT NOT NULL,
                        subject_id VARCHAR(80) NOT NULL,
                        PRIMARY KEY (lyric_id, subject_id)
                    )
                    """);
            for (String[] subject : List.of(
                    new String[] { "madina", "Madina" },
                    new String[] { "prophet", "Prophet ﷺ" },
                    new String[] { "ramadan", "Ramadan" },
                    new String[] { "eid", "Eid" },
                    new String[] { "legacy-karbala", "Karbala" },
                    new String[] { "namaz", "Namaz" },
                    new String[] { "mercy", "Mercy" },
                    new String[] { "tawakkul", "Tawakkul" })) {
                try (PreparedStatement insert = connection.prepareStatement(
                        "INSERT INTO lyric_subjects (id, name) VALUES (?, ?)")) {
                    insert.setString(1, subject[0]);
                    insert.setString(2, subject[1]);
                    insert.executeUpdate();
                }
                try (PreparedStatement insert = connection.prepareStatement(
                        "INSERT INTO subject_numeric_mappings (subject_key) VALUES (?)")) {
                    insert.setString(1, subject[0]);
                    insert.executeUpdate();
                }
            }
            statement.executeUpdate(
                    "INSERT INTO lyric_subject_assignments (lyric_id, subject_id) VALUES (23, 'legacy-karbala')");
            long existingKarbalaMapping = mappingId(connection, "legacy-karbala");

            V17__seed_lyric_subjects.apply(connection);
            V17__seed_lyric_subjects.apply(connection);

            assertEquals(36, count(connection, "lyric_subjects"));
            assertEquals(36, count(connection, "subject_numeric_mappings"));
            assertEquals(existingKarbalaMapping, mappingId(connection, "legacy-karbala"));
            assertEquals(1, countAssignments(connection));
            assertEquals("legacy-karbala", assignmentSubject(connection));
            assertEquals(0, countById(connection, "karbala"));
            assertEquals(1, countByName(connection, "Karbala"));
            assertEquals(1, countById(connection, "ramadan"));
            assertEquals(1, countById(connection, "ramzan"));
            assertEquals(1, countById(connection, "eid"));
            assertEquals(1, countById(connection, "eid-ul-fitr"));
            for (String id : List.of(
                    "safar-e-madina", "gham-e-madina", "hajj", "umrah", "ramzan", "muharram",
                    "sehra", "nikah", "maa-baap", "maut", "aakhirat", "tauba", "dua", "isteghasa",
                    "ishq-e-rasool", "shan-e-mustafa", "meraj-un-nabi", "ahl-e-bait", "sahaba-e-kiram",
                    "manqabat-e-ala-hazrat", "manqabat-e-ghaus-e-azam",
                    "manqabat-e-khwaja-garib-nawaz", "eid-milad-un-nabi", "urs-e-razavi",
                    "shab-e-baraat", "eid-ul-adha", "youm-e-ashura")) {
                assertEquals(1, countById(connection, id), "Missing subject " + id);
            }
        }
    }

    private static int count(Connection connection, String table) throws Exception {
        try (Statement statement = connection.createStatement();
                ResultSet result = statement.executeQuery("SELECT COUNT(*) FROM " + table)) {
            result.next();
            return result.getInt(1);
        }
    }

    private static long mappingId(Connection connection, String subjectId) throws Exception {
        try (PreparedStatement statement = connection.prepareStatement(
                "SELECT id FROM subject_numeric_mappings WHERE subject_key = ?")) {
            statement.setString(1, subjectId);
            try (ResultSet result = statement.executeQuery()) {
                result.next();
                return result.getLong(1);
            }
        }
    }

    private static int countAssignments(Connection connection) throws Exception {
        return count(connection, "lyric_subject_assignments");
    }

    private static String assignmentSubject(Connection connection) throws Exception {
        try (Statement statement = connection.createStatement();
                ResultSet result = statement.executeQuery(
                        "SELECT subject_id FROM lyric_subject_assignments WHERE lyric_id = 23")) {
            result.next();
            return result.getString(1);
        }
    }

    private static int countById(Connection connection, String subjectId) throws Exception {
        try (PreparedStatement statement = connection.prepareStatement(
                "SELECT COUNT(*) FROM lyric_subjects WHERE id = ?")) {
            statement.setString(1, subjectId);
            try (ResultSet result = statement.executeQuery()) {
                result.next();
                return result.getInt(1);
            }
        }
    }

    private static int countByName(Connection connection, String subjectName) throws Exception {
        try (PreparedStatement statement = connection.prepareStatement(
                "SELECT COUNT(*) FROM lyric_subjects WHERE name = ?")) {
            statement.setString(1, subjectName);
            try (ResultSet result = statement.executeQuery()) {
                result.next();
                return result.getInt(1);
            }
        }
    }
}
