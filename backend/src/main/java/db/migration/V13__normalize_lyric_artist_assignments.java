package db.migration;

import org.flywaydb.core.api.migration.BaseJavaMigration;
import org.flywaydb.core.api.migration.Context;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

public class V13__normalize_lyric_artist_assignments extends BaseJavaMigration {

    private boolean mysql;

    @Override
    public void migrate(Context context) throws Exception {
        Connection connection = context.getConnection();
        String product = connection.getMetaData().getDatabaseProductName();
        mysql = product.toLowerCase().contains("mysql");
        if (!mysql && !product.equalsIgnoreCase("H2")) {
            throw new IllegalStateException("V13 supports MySQL and H2, not " + product + ".");
        }

        List<ArtistRecord> artists = readArtists(connection);
        Map<String, Long> numericIds = readNumericMappings(connection);
        long nextId = numericIds.values().stream().mapToLong(Long::longValue).max().orElse(0L);
        for (ArtistRecord artist : artists) {
            if (!numericIds.containsKey(artist.key())) {
                numericIds.put(artist.key(), ++nextId);
            }
        }

        createArtistAndRoleStagingTables(connection);
        copyArtists(connection, artists, numericIds);
        copyRoles(connection, numericIds);
        verifyEqualCounts(connection, "artists", "artists_v13", "artist records");
        verifyEqualCounts(connection, "artist_roles", "artist_roles_v13", "artist roles");
        replaceArtistTables(connection);
        replaceLyricArtistTable(connection);
        backfillAssignments(connection);
    }

    private List<ArtistRecord> readArtists(Connection connection) throws SQLException {
        List<ArtistRecord> artists = new ArrayList<>();
        try (Statement statement = connection.createStatement();
                ResultSet result = statement.executeQuery("""
                        SELECT id, full_name, display_name, biography, status, created_at, updated_at
                        FROM artists ORDER BY id
                        """)) {
            while (result.next()) {
                artists.add(new ArtistRecord(
                        result.getString("id"),
                        result.getString("full_name"),
                        result.getString("display_name"),
                        result.getString("biography"),
                        result.getString("status"),
                        result.getTimestamp("created_at"),
                        result.getTimestamp("updated_at")));
            }
        }
        return artists;
    }

    private Map<String, Long> readNumericMappings(Connection connection) throws SQLException {
        Map<String, Long> mappings = new HashMap<>();
        try (Statement statement = connection.createStatement();
                ResultSet result = statement.executeQuery(
                        "SELECT id, artist_key FROM artist_numeric_mappings")) {
            while (result.next()) {
                mappings.put(result.getString("artist_key"), result.getLong("id"));
            }
        }
        return mappings;
    }

    private void createArtistAndRoleStagingTables(Connection connection) throws SQLException {
        execute(connection, """
                CREATE TABLE artists_v13 (
                    id BIGINT %s NOT NULL,
                    artist_key VARCHAR(120) NOT NULL,
                    full_name VARCHAR(200) NOT NULL,
                    display_name VARCHAR(200) NULL,
                    biography TEXT NULL,
                    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
                    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT pk_artists_v13 PRIMARY KEY (id),
                    CONSTRAINT uq_artists_v13_key UNIQUE (artist_key),
                    CONSTRAINT ck_artists_v13_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
                )
                """.formatted(mysql ? "AUTO_INCREMENT" : "GENERATED BY DEFAULT AS IDENTITY"));
        execute(connection, """
                CREATE TABLE artist_roles_v13 (
                    artist_id BIGINT NOT NULL,
                    role VARCHAR(20) NOT NULL,
                    CONSTRAINT pk_artist_roles_v13 PRIMARY KEY (artist_id, role),
                    CONSTRAINT ck_artist_role_v13 CHECK (
                        role IN ('SINGER','WRITER','LYRICIST','POET','RECITER','NAAT_KHWAN','COMPOSER','OTHER'))
                )
                """);
    }

    private void copyArtists(
            Connection connection,
            List<ArtistRecord> artists,
            Map<String, Long> numericIds) throws SQLException {
        try (PreparedStatement insert = connection.prepareStatement("""
                INSERT INTO artists_v13
                    (id, artist_key, full_name, display_name, biography, status, created_at, updated_at)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?)
                """)) {
            for (ArtistRecord artist : artists) {
                insert.setLong(1, numericIds.get(artist.key()));
                insert.setString(2, artist.key());
                insert.setString(3, artist.fullName());
                insert.setString(4, artist.displayName());
                insert.setString(5, artist.biography());
                insert.setString(6, artist.status());
                insert.setTimestamp(7, artist.createdAt());
                insert.setTimestamp(8, artist.updatedAt());
                insert.addBatch();
            }
            insert.executeBatch();
        }
    }

    private void copyRoles(Connection connection, Map<String, Long> numericIds) throws SQLException {
        try (Statement statement = connection.createStatement();
                ResultSet result = statement.executeQuery("SELECT artist_id, role FROM artist_roles");
                PreparedStatement insert = connection.prepareStatement(
                        "INSERT INTO artist_roles_v13 (artist_id, role) VALUES (?, ?)")) {
            while (result.next()) {
                Long artistId = numericIds.get(result.getString("artist_id"));
                if (artistId == null) {
                    throw new IllegalStateException("An artist role has no matching artist.");
                }
                insert.setLong(1, artistId);
                insert.setString(2, result.getString("role"));
                insert.addBatch();
            }
            insert.executeBatch();
        }
    }

    private void replaceArtistTables(Connection connection) throws SQLException {
        dropForeignKey(connection, "artist_roles", "fk_artist_role_artist");
        dropForeignKey(connection, "artist_numeric_mappings", "fk_artist_numeric_mapping_artist");
        execute(connection, "DROP TABLE artist_roles");

        if (mysql) {
            execute(connection, "RENAME TABLE artists TO artists_legacy_v13, artists_v13 TO artists");
        } else {
            execute(connection, "ALTER TABLE artists RENAME TO artists_legacy_v13");
            execute(connection, "ALTER TABLE artists_v13 RENAME TO artists");
        }

        execute(connection, """
                INSERT INTO artist_numeric_mappings (id, artist_key)
                SELECT a.id, a.artist_key FROM artists a
                LEFT JOIN artist_numeric_mappings m ON m.artist_key = a.artist_key
                WHERE m.id IS NULL
                """);
        verifyEqualCounts(connection, "artists", "artist_numeric_mappings", "artist mappings");
        if (count(connection, """
                SELECT COUNT(*) FROM artist_numeric_mappings m
                LEFT JOIN artists a ON a.id = m.id AND a.artist_key = m.artist_key
                WHERE a.id IS NULL
                """) != 0) {
            throw new IllegalStateException("Artist numeric mappings do not match the canonical artist records.");
        }
        execute(connection, """
                ALTER TABLE artist_numeric_mappings
                ADD CONSTRAINT fk_artist_numeric_mapping_artist
                FOREIGN KEY (id) REFERENCES artists (id) ON DELETE CASCADE
                """);
        execute(connection, """
                ALTER TABLE artist_numeric_mappings
                ADD CONSTRAINT fk_artist_numeric_mapping_artist_key
                FOREIGN KEY (artist_key) REFERENCES artists (artist_key) ON DELETE CASCADE
                """);
        if (mysql) {
            execute(connection, "RENAME TABLE artist_roles_v13 TO artist_roles");
        } else {
            execute(connection, "ALTER TABLE artist_roles_v13 RENAME TO artist_roles");
        }
        execute(connection, """
                ALTER TABLE artist_roles
                ADD CONSTRAINT fk_artist_role_artist
                FOREIGN KEY (artist_id) REFERENCES artists (id) ON DELETE CASCADE
                """);
        execute(connection, "CREATE INDEX idx_artist_roles_role ON artist_roles (role)");
        execute(connection, "DROP TABLE artists_legacy_v13");
    }

    private void replaceLyricArtistTable(Connection connection) throws SQLException {
        if (mysql) {
            execute(connection, "RENAME TABLE lyric_artist_ids TO lyric_artist_ids_legacy");
        } else {
            execute(connection, "ALTER TABLE lyric_artist_ids RENAME TO lyric_artist_ids_legacy");
        }
        execute(connection, """
                CREATE TABLE lyric_artist_ids (
                    lyric_id BIGINT NOT NULL,
                    artist_id BIGINT NOT NULL,
                    role VARCHAR(20) NOT NULL,
                    position INT NULL,
                    CONSTRAINT pk_lyric_artist_assignment PRIMARY KEY (lyric_id, artist_id, role),
                    CONSTRAINT fk_lyric_artist_lyric_v13 FOREIGN KEY (lyric_id)
                        REFERENCES lyrics (id) ON DELETE RESTRICT,
                    CONSTRAINT fk_lyric_artist_artist_v13 FOREIGN KEY (artist_id)
                        REFERENCES artists (id) ON DELETE RESTRICT,
                    CONSTRAINT ck_lyric_artist_role CHECK (role IN ('WRITER', 'RECITER')),
                    CONSTRAINT ck_lyric_artist_position CHECK (
                        (role = 'WRITER' AND position IS NULL)
                        OR (role = 'RECITER' AND position IS NOT NULL AND position >= 0)
                    )
                )
                """);
        execute(connection, "CREATE INDEX idx_lyric_artist_role_lookup ON lyric_artist_ids (artist_id, role, lyric_id)");
        execute(connection, "CREATE INDEX idx_lyric_artist_order ON lyric_artist_ids (lyric_id, role, position)");
    }

    private void backfillAssignments(Connection connection) throws SQLException {
        execute(connection, """
                INSERT IGNORE INTO lyric_artist_ids (lyric_id, artist_id, role, position)
                SELECT l.id, a.id, 'WRITER', NULL
                FROM lyrics l
                JOIN artists a ON a.artist_key = l.writer_id
                JOIN artist_roles ar ON ar.artist_id = a.id
                    AND ar.role IN ('WRITER', 'LYRICIST', 'POET')
                WHERE l.writer_id IS NOT NULL AND l.writer_id <> ''
                """);
        execute(connection, """
                INSERT IGNORE INTO lyric_artist_ids (lyric_id, artist_id, role, position)
                SELECT r.lyric_id, matched.artist_id, 'RECITER', r.position
                FROM lyric_reciters r
                JOIN (
                    SELECT LOWER(TRIM(candidate_name)) AS normalized_name, MIN(id) AS artist_id
                    FROM (
                        SELECT id, full_name AS candidate_name FROM artists
                        UNION ALL
                        SELECT id, display_name AS candidate_name FROM artists WHERE display_name IS NOT NULL
                    ) names
                    GROUP BY LOWER(TRIM(candidate_name))
                    HAVING COUNT(DISTINCT id) = 1
                ) matched ON matched.normalized_name = LOWER(TRIM(r.display_name))
                JOIN artist_roles ar ON ar.artist_id = matched.artist_id
                    AND ar.role IN ('RECITER', 'NAAT_KHWAN')
                """);
        execute(connection, """
                INSERT IGNORE INTO lyric_artist_ids (lyric_id, artist_id, role, position)
                SELECT legacy.lyric_id, a.id,
                       CASE
                           WHEN MAX(CASE WHEN ar.role IN ('WRITER', 'LYRICIST', 'POET') THEN 1 ELSE 0 END) = 1
                                AND MAX(CASE WHEN ar.role IN ('RECITER', 'NAAT_KHWAN') THEN 1 ELSE 0 END) = 0
                           THEN 'WRITER'
                           ELSE 'RECITER'
                       END,
                       CASE
                           WHEN MAX(CASE WHEN ar.role IN ('WRITER', 'LYRICIST', 'POET') THEN 1 ELSE 0 END) = 1
                                AND MAX(CASE WHEN ar.role IN ('RECITER', 'NAAT_KHWAN') THEN 1 ELSE 0 END) = 0
                           THEN NULL
                           ELSE ROW_NUMBER() OVER (PARTITION BY legacy.lyric_id ORDER BY a.id) - 1
                       END
                FROM lyric_artist_ids_legacy legacy
                JOIN artists a ON a.artist_key = legacy.artist_id
                JOIN artist_roles ar ON ar.artist_id = a.id
                GROUP BY legacy.lyric_id, a.id
                HAVING (MAX(CASE WHEN ar.role IN ('WRITER', 'LYRICIST', 'POET') THEN 1 ELSE 0 END) = 1
                        AND MAX(CASE WHEN ar.role IN ('RECITER', 'NAAT_KHWAN') THEN 1 ELSE 0 END) = 0)
                    OR (MAX(CASE WHEN ar.role IN ('WRITER', 'LYRICIST', 'POET') THEN 1 ELSE 0 END) = 0
                        AND MAX(CASE WHEN ar.role IN ('RECITER', 'NAAT_KHWAN') THEN 1 ELSE 0 END) = 1)
                """);
        execute(connection, """
                INSERT IGNORE INTO lyric_artist_ids (lyric_id, artist_id, role, position)
                SELECT l.id, a.id,
                       CASE
                           WHEN MAX(CASE WHEN ar.role IN ('WRITER', 'LYRICIST', 'POET') THEN 1 ELSE 0 END) = 1
                                AND MAX(CASE WHEN ar.role IN ('RECITER', 'NAAT_KHWAN') THEN 1 ELSE 0 END) = 0
                           THEN 'WRITER'
                           ELSE 'RECITER'
                       END,
                       CASE
                           WHEN MAX(CASE WHEN ar.role IN ('WRITER', 'LYRICIST', 'POET') THEN 1 ELSE 0 END) = 1
                                AND MAX(CASE WHEN ar.role IN ('RECITER', 'NAAT_KHWAN') THEN 1 ELSE 0 END) = 0
                           THEN NULL
                           ELSE 0
                       END
                FROM lyrics l
                JOIN artists a ON a.artist_key = l.artist_id
                JOIN artist_roles ar ON ar.artist_id = a.id
                WHERE l.artist_id IS NOT NULL AND l.artist_id <> ''
                GROUP BY l.id, a.id
                HAVING (MAX(CASE WHEN ar.role IN ('WRITER', 'LYRICIST', 'POET') THEN 1 ELSE 0 END) = 1
                        AND MAX(CASE WHEN ar.role IN ('RECITER', 'NAAT_KHWAN') THEN 1 ELSE 0 END) = 0)
                    OR (MAX(CASE WHEN ar.role IN ('WRITER', 'LYRICIST', 'POET') THEN 1 ELSE 0 END) = 0
                        AND MAX(CASE WHEN ar.role IN ('RECITER', 'NAAT_KHWAN') THEN 1 ELSE 0 END) = 1)
                """);
        execute(connection, """
                DELETE FROM lyric_artist_ids_legacy
                WHERE EXISTS (
                    SELECT 1
                    FROM artists a
                    JOIN lyric_artist_ids la ON la.artist_id = a.id
                    WHERE la.lyric_id = lyric_artist_ids_legacy.lyric_id
                      AND a.artist_key = lyric_artist_ids_legacy.artist_id
                )
                """);
        execute(connection, """
                DELETE FROM lyric_reciters
                WHERE EXISTS (
                    SELECT 1
                    FROM lyric_artist_ids la
                    JOIN artists a ON a.id = la.artist_id
                    WHERE la.lyric_id = lyric_reciters.lyric_id
                      AND la.role = 'RECITER'
                      AND (LOWER(TRIM(a.full_name)) = LOWER(TRIM(lyric_reciters.display_name))
                           OR LOWER(TRIM(a.display_name)) = LOWER(TRIM(lyric_reciters.display_name)))
                )
                """);
    }

    private void dropForeignKey(Connection connection, String table, String constraint) throws SQLException {
        execute(connection, mysql
                ? "ALTER TABLE " + table + " DROP FOREIGN KEY " + constraint
                : "ALTER TABLE " + table + " DROP CONSTRAINT " + constraint);
    }

    private void execute(Connection connection, String sql) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    private void verifyEqualCounts(Connection connection, String first, String second, String description)
            throws SQLException {
        if (count(connection, "SELECT COUNT(*) FROM " + first)
                != count(connection, "SELECT COUNT(*) FROM " + second)) {
            throw new IllegalStateException("Copied " + description + " do not match the source count.");
        }
    }

    private long count(Connection connection, String sql) throws SQLException {
        try (Statement statement = connection.createStatement();
                ResultSet result = statement.executeQuery(sql)) {
            result.next();
            return result.getLong(1);
        }
    }

    private record ArtistRecord(
            String key,
            String fullName,
            String displayName,
            String biography,
            String status,
            java.sql.Timestamp createdAt,
            java.sql.Timestamp updatedAt) {
    }
}
